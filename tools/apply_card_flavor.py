def main() -> None:
    with io.open(CARDS_PATH, "r", encoding="utf-8-sig") as handle:
        cards = json.load(handle)
    assert isinstance(cards, list) and len(cards) == 60, len(cards)
    missing = []
    for card in cards:
        flavor = FLAVOR.get(card["id"])
        if flavor is None:
            missing.append(card["id"])
            continue
        move_name, fallacy, lesson, target, reply = flavor
        card["move"] = {"name": move_name, "fallacy": fallacy, "lesson": lesson}
        if target:
            card["target"] = target
        else:
            card.pop("target", None)
        if reply and card["type"] != "CONSTRUCTION":
            card["reply"] = reply
        else:
            card.pop("reply", None)
    if missing:
        raise SystemExit("missing flavor for: %s" % ", ".join(missing))
    with io.open(CARDS_PATH, "w", encoding="utf-8", newline="\n") as handle:
        json.dump(cards, handle, ensure_ascii=False, indent=2)
        handle.write("\n")
    print("flavored %d cards" % len(cards))


if __name__ == "__main__":
    main()
